alter table caja_turno add column if not exists numero bigint;
alter table caja_turno add column if not exists arqueo jsonb;

-- Los de antes, por orden de apertura.
update caja_turno t set numero = s.n
  from (select id, row_number() over (order by abierto_en, id) as n from caja_turno) s
 where s.id = t.id and t.numero is null;

do $$
begin
  if not exists (select 1 from information_schema.columns
                  where table_name = 'caja_turno' and column_name = 'numero' and is_identity = 'YES') then
    execute 'alter table caja_turno alter column numero add generated by default as identity';
    perform setval(pg_get_serial_sequence('caja_turno', 'numero'), (select coalesce(max(numero), 0) + 1 from caja_turno), false);
  end if;
end $$;

alter table caja_turno alter column numero set not null;
create unique index if not exists uq_caja_turno_numero on caja_turno (numero);
