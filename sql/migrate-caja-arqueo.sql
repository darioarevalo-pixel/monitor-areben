-- 🔑 `numero`: correlativo, ⛔ el uuid (se tipea a mano si el lector falla). Los cierres que YA existen se numeran por
--    orden de apertura (1, 2, 3…) y los nuevos siguen solos (identidad). Único por base: cada base tiene UNA marca.
-- 🔑 `arqueo`: la foto del sobre, ⛔ toca el cierre (`contado`/`esperado` quedan como estaban):
--    `{ estado: 'bien' | 'diferencia', esperado, contado, diferencia, nota, por, por_usuario, en }`. null = sin recibir.
-- 🔑 Sin trigger: el de auditoría (`caja_turno_abierto_chk`) frena INSERT de ventas y movimientos en un turno cerrado;
--    el arqueo es un UPDATE de un turno cerrado, que lo cuida el handler (sólo admin, sólo cerrado). Sin GRANT al rol
--    `motor`: la Caja lee por supabase-js.
--
-- ROLLBACK:
